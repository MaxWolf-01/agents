"""Checks for scan_sessions.py, the scanner /restore-sessions classifies sessions from. Run: uv run test_scan_sessions.py

The seam is the command, run as the skill runs it (`uv run scan_sessions.py`), over a sessions
directory of transcripts written the way Claude Code writes them. The oracle is the script's own
docstring, which the skill puts in front of the classifying agent as the meaning of each field:
which files it skips, the order, the JSON fields and what each one counts.
"""

import json
import os
import subprocess
import sys
import time
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parent / "scan_sessions.py"
PADDING = {"type": "user", "message": {"role": "user", "content": [{"type": "tool_result", "content": "x" * 3200}]}}


def said(role: str, text: str, **entry: object) -> dict:
    return {"type": role, "message": {"role": role, "content": [{"type": "text", "text": text}]}, **entry}


def prompt(text: str, **entry: object) -> dict:
    """A user prompt, which Claude Code writes as a plain string."""
    return {"type": "user", "message": {"role": "user", "content": text}, **entry}


def ran(command: str) -> dict:
    return {"type": "assistant", "message": {"role": "assistant", "content": [
        {"type": "tool_use", "name": "Bash", "input": {"command": command}}]}}


def transcript(directory: Path, session: str, *entries: dict, tail: str = "") -> Path:
    """A transcript over the 3KB a trivial session stays under: the entries, a long tool result, and
    `tail` written after them as it is."""
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{session}.jsonl"
    path.write_text("".join(json.dumps(e) + "\n" for e in (*entries, PADDING)) + tail)
    return path


def scan(*args: str, cwd: Path | None = None, **env: str) -> subprocess.CompletedProcess:
    clean = {k: v for k, v in os.environ.items() if k not in ("CLAUDE_CODE_SESSION_ID", "CLAUDE_CONFIG_DIR")}
    return subprocess.run(["uv", "run", "--quiet", str(SCRIPT), *args], cwd=cwd, capture_output=True, text=True,
                          timeout=120, env={**clean, **env})


def scanned(*args: str, **kw) -> list[dict]:
    done = scan(*args, **kw)
    assert done.returncode == 0, done.stderr
    return json.loads(done.stdout)


def test_a_session_reads_as_its_topic_its_last_words_and_what_it_finished(tmp_path: Path) -> None:
    """A live session's last line may be half written; the lines before it are still read."""
    transcript(
        tmp_path, "s1",
        prompt("<command-message>mx:task</command-message>\n<command-name>/mx:task</command-name>\n"
               "<command-args>fix   the ledger's second bank</command-args>"),
        prompt("<system-reminder>a reminder the harness injected</system-reminder>"),
        prompt("Caveat: the messages below were generated by a command", isMeta=True),
        said("assistant", "Looking at the ledger's second bank now."),
        ran("git commit -m 'fix the second bank'"),
        prompt("and now the   third bank, please"),
        said("assistant", "The third bank balances too; nothing more to do."),
        tail='{"type": "assistant", "message": {"role": "assis',
    )
    [s] = scanned(str(tmp_path))
    assert s["session_id"] == "s1"
    assert s["first_user"] == "mx:task /mx:task fix the ledger's second bank"
    assert s["last_user"] == "and now the third bank, please"
    assert s["last_assistant"] == "The third bank balances too; nothing more to do."
    assert s["user_msgs_substantive"] == 2, "the reminder and the meta message are not the user's"
    assert s["signals"] == {"commit": True, "transcribe": False, "handoff": False}
    assert s["interrupted"] is False


def test_a_session_whose_last_message_is_an_interruption_reads_as_interrupted(tmp_path: Path) -> None:
    transcript(tmp_path, "s1", prompt("rename the ledger's banks"), said("assistant", "Renaming the first bank now."),
               said("user", "[Request interrupted by user for tool use]"))
    [s] = scanned(str(tmp_path))
    assert s["interrupted"] is True
    assert s["last_user"] == "rename the ledger's banks", "an interruption is no message of the user's"


# Each completion signal, seen as a tool call or claimed in the assistant's text.
SIGNALS = {
    "a commit run": ("commit", ran("git push origin main")),
    "a commit claimed": ("commit", said("assistant", "Committed the ledger fix as a1b2c3d.")),
    "a transcript run": ("transcribe", ran("transcribe meeting.m4a")),
    "a transcript claimed": ("transcribe", said("assistant", "Transcript saved to notes/meeting.md.")),
    "a handoff run": ("handoff", ran("cat > agent/handoffs/2026-10-06-ledger.md")),
    "a handoff claimed": ("handoff", said("assistant", "Handoff written to agent/handoffs/2026-10-06-ledger.md.")),
}


@pytest.mark.parametrize("signal, entry", SIGNALS.values(), ids=SIGNALS)
def test_each_completion_signal_is_read_from_a_tool_call_or_the_assistants_claim(tmp_path: Path, signal: str, entry: dict) -> None:
    transcript(tmp_path, "s1", prompt("finish the ledger work"), entry)
    [s] = scanned(str(tmp_path))
    assert s["signals"] == {name: name == signal for name in ("commit", "transcribe", "handoff")}


def test_the_scan_skips_trivial_files_subagents_and_the_sessions_left_out_and_lists_newest_first(tmp_path: Path) -> None:
    now = time.time()
    # hours since each session last ran, in no order a directory listing would give by chance
    ago = {"ledger": 3, "lamp": 1, "oven": 4, "bank": 2, "excluded": 0, "scanning": 0, "stale": 24 * 5}
    for session, hours in ago.items():
        path = transcript(tmp_path, session, prompt(f"work on the {session}"))
        os.utime(path, (now - 3600 * hours,) * 2)
    trivial = tmp_path / "trivial.jsonl"
    trivial.write_text(json.dumps(prompt("hello there, ledger")) + "\n")
    # older than the two --sessions keeps: whether a skipped file counts toward that limit, the docstring leaves open
    os.utime(trivial, (now - 3600 * 10,) * 2)
    transcript(tmp_path / "lamp" / "subagents", "agent-a1", prompt("a subagent's own task"))
    ids = lambda *args: [s["session_id"] for s in scanned(str(tmp_path), "--exclude", "excluded", *args,
                                                           CLAUDE_CODE_SESSION_ID="scanning")]
    assert ids() == ["lamp", "bank", "ledger", "oven", "stale"]
    assert ids("--sessions", "2") == ["lamp", "bank"]
    assert ids("--days", "1") == ["lamp", "bank", "ledger", "oven"]


def test_without_a_directory_the_scan_reads_the_current_directorys_project(tmp_path: Path) -> None:
    project = tmp_path / "lamp.repo"
    project.mkdir()
    config = tmp_path / "config"
    dashed = "".join(c if c.isalnum() else "-" for c in str(project.resolve()))
    transcript(config / "projects" / dashed, "s1", prompt("work on the ledger"))
    assert [s["session_id"] for s in scanned(cwd=project, CLAUDE_CONFIG_DIR=str(config))] == ["s1"]
    elsewhere = tmp_path / "elsewhere"
    elsewhere.mkdir()
    done = scan(cwd=elsewhere, CLAUDE_CONFIG_DIR=str(config))
    assert done.returncode == 1 and str(config / "projects") in done.stderr, "a project with no sessions says where it looked"


if __name__ == "__main__":
    sys.exit(pytest.main([__file__, "-q"]))
